<h1>Child Safety & Protection Policy</h1>

<p class="subtitle">
At Linkup, protecting children and preventing child sexual abuse and exploitation is a fundamental
responsibility. We are committed to maintaining a safe and respectful digital environment and have
zero tolerance for any form of child abuse, exploitation, grooming, or content that endangers minors.
</p>

<div class="highlight">
<strong>Zero-Tolerance Commitment:</strong>
Linkup strictly prohibits Child Sexual Abuse and Exploitation (CSAE), including Child Sexual Abuse
Material (CSAM), child grooming, sexual exploitation of minors, trafficking, harassment, or any other
behavior that threatens the safety, dignity, or well-being of children.
</div>

<h2>Prohibition of Child Sexual Abuse and Exploitation</h2>

<p>
Linkup strictly prohibits the creation, upload, sharing, distribution, solicitation, promotion,
possession, or facilitation of any content or activity involving the sexual abuse or exploitation
of children.
</p>

<p>
This prohibition includes, but is not limited to, Child Sexual Abuse Material (CSAM), sexual
exploitation of minors, child grooming, sexual solicitation of children, trafficking of minors,
and any attempt to facilitate or encourage such conduct.
</p>

<p>
Any user, account, content, or activity found to be involved in Child Sexual Abuse and Exploitation
(CSAE) will be subject to immediate enforcement action.
</p>

<h2>Our Child Safety Standards</h2>

<ul>

<li>
<strong>Zero tolerance for CSAE:</strong>
Linkup strictly prohibits Child Sexual Abuse and Exploitation (CSAE) and all related activities.
</li>

<li>
<strong>CSAM prohibition:</strong>
The creation, upload, storage, sharing, distribution, solicitation, or promotion of Child Sexual
Abuse Material (CSAM) is strictly prohibited.
</li>

<li>
<strong>Grooming prohibition:</strong>
Any attempt to groom, manipulate, solicit, or sexually exploit a child through Linkup is strictly
prohibited.
</li>

<li>
<strong>Immediate enforcement:</strong>
Content or accounts that violate our child safety standards may be removed or permanently disabled
without prior notice.
</li>

<li>
<strong>User reporting:</strong>
Users can report content, accounts, messages, or other behavior that they believe violates child
safety standards through the available reporting mechanisms on Linkup.
</li>

<li>
<strong>Investigation:</strong>
Reports involving child safety are reviewed promptly and appropriate action is taken based on the
nature and severity of the reported activity.
</li>

<li>
<strong>Account termination:</strong>
Accounts found to be involved in child sexual abuse, exploitation, grooming, or related prohibited
activities may be permanently terminated.
</li>

<li>
<strong>Legal cooperation:</strong>
Linkup may cooperate with law enforcement agencies, regulatory authorities, and other appropriate
organizations when required by applicable law or when necessary to protect children from abuse or
exploitation.
</li>

<li>
<strong>Continuous improvement:</strong>
We continuously review and improve our safety practices, moderation processes, and reporting
mechanisms to strengthen child protection on the platform.
</li>

</ul>

